package algoritmos

import kotlin.math.*

fun main() {
    println("Testando hierarquia no UAL")
    println("12 + 5 / 2 = " + (12 + 5 / 2.0))
    println("(12 + 5) / 2 = " + ((12 + 5) / 2.0))
    println("64**1 / 4 = " + (64.0.pow(1) / 4))
    println("64**(1 / 4) = " + 64.0.pow(1.0 / 4))
    println("3 * (7 % 5) = " + (3 * (7 % 5)))
    println("(3 * 7) % 5 = " + ((3 * 7) % 5))
    println("(3 * 7) div 5 = " + ((3 * 7) / 5))
}
